// Packs the recorded sounds in tools/sounds/<set>/*.mp3 (credits in CREDITS.md there) into
// src/audio/<set>Sounds.js (export <SET>_SOUNDS) as base64, so the single-file build carries them.
// Sets: kart (the ATK Kart), jeep (its driver's "oof").
// Usage: node tools/pack_sounds.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

for (const set of readdirSync('tools/sounds').sort()) {
  const dir = `tools/sounds/${set}`;
  const files = readdirSync(dir).filter((f) => f.endsWith('.mp3')).sort();
  if (!files.length) continue;
  let out = `// TURBO PITCH — generated by tools/pack_sounds.mjs from ${dir} (do not edit).\n`;
  out += `// Real recordings, CC0 (BigSoundBank); see ${dir}/CREDITS.md.\n`;
  out += `export const ${set.toUpperCase()}_SOUNDS = {\n`;
  for (const f of files) out += `  ${f.replace('.mp3', '')}: '${readFileSync(`${dir}/${f}`).toString('base64')}',\n`;
  out += '};\n';
  writeFileSync(`src/audio/${set}Sounds.js`, out);
  console.log(`src/audio/${set}Sounds.js: ${files.length} sounds, ${(out.length / 1024).toFixed(0)} KB`);
}
