// Packs the kart's recorded sounds (tools/sounds/kart/*.mp3, credits in CREDITS.md there) into
// src/audio/kartSounds.js as base64, so the single-file build carries them.
// Usage: node tools/pack_sounds.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const dir = 'tools/sounds/kart';
const files = readdirSync(dir).filter((f) => f.endsWith('.mp3')).sort();
let out = '// TURBO PITCH — generated by tools/pack_sounds.mjs from tools/sounds/kart (do not edit).\n';
out += '// Real recordings, CC0 (BigSoundBank); see tools/sounds/kart/CREDITS.md.\n';
out += 'export const KART_SOUNDS = {\n';
for (const f of files) out += `  ${f.replace('.mp3', '')}: '${readFileSync(`${dir}/${f}`).toString('base64')}',\n`;
out += '};\n';
writeFileSync('src/audio/kartSounds.js', out);
console.log(`src/audio/kartSounds.js: ${files.length} sounds, ${(out.length / 1024).toFixed(0)} KB`);
